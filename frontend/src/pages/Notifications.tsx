import { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { AlarmClock, Bell, CalendarClock, CheckCheck, ClipboardCheck, FileClock, Mail, Truck, Wallet } from 'lucide-react'
import { api } from '../lib/api'
import { relative, dateTime } from '../lib/format'
import { Badge, Empty, Field, Pagination, QueryState, Select, errorMessage, useToast } from '../components/ui'
import { PageHead } from '../components/Layout'

const ICONS: Record<string, any> = {
  progress_reminder: AlarmClock, task_overdue: ClipboardCheck, task_due_soon: ClipboardCheck, task_assigned: ClipboardCheck,
  project_deadline: CalendarClock, project_overdue: CalendarClock, quotation_expiry: FileClock, payment_overdue: Wallet,
  pending_approval: FileClock, supplier_delay: Truck, missing_update: AlarmClock, event_reminder: CalendarClock,
}
const EMAIL_LABEL: Record<string, string> = { sent: 'Email sent', pending: 'Email queued', failed: 'Email failed', not_configured: 'In-app only (email not configured)', not_requested: 'In-app only' }

export default function NotificationsPage() {
  const nav = useNavigate()
  const qc = useQueryClient()
  const toast = useToast()
  const [unread, setUnread] = useState(false)
  const [type, setType] = useState('')
  const [page, setPage] = useState(1)
  const types = useQuery({ queryKey: ['settings-me'], queryFn: () => api.get('/api/settings/me') })
  const q = useQuery({ queryKey: ['notifications', unread, type, page], queryFn: () => api.get('/api/notifications', { unread, type, page, page_size: 30 }) })
  const refresh = () => { qc.invalidateQueries({ queryKey: ['notifications'] }); qc.invalidateQueries({ queryKey: ['unread-count'] }) }
  const mark = useMutation({ mutationFn: ({ id, read }: { id: number; read: boolean }) => api.post(`/api/notifications/${id}/read`, {}, { read }), onSuccess: refresh })
  const all = useMutation({
    mutationFn: () => api.post('/api/notifications/read-all', {}),
    onSuccess: (r: any) => { toast(`${r.updated} notification(s) marked as read`); refresh() },
    onError: (e) => toast(errorMessage(e), 'error'),
  })
  const typeOpts = Object.entries((types.data?.notification_types ?? {}) as Record<string, string>).map(([value, label]) => ({ value, label }))
  return (
    <>
      <PageHead title="Notifications" sub="Reminders and alerts generated by the scheduler and by changes in your projects."
        actions={<button className="btn" disabled={all.isPending} onClick={() => all.mutate()}><CheckCheck size={16} /> Mark all as read</button>} />
      <div className="card">
        <div className="filters">
          <Field label="Type"><Select value={type} onChange={(v) => { setType(v); setPage(1) }} options={typeOpts} placeholder="All types" /></Field>
          <label className="checkbox"><input type="checkbox" checked={unread} onChange={(e) => { setUnread(e.target.checked); setPage(1) }} /> Unread only</label>
        </div>
        <QueryState q={q}>
          {q.data?.items.length === 0 ? <Empty icon={<Bell size={36} />} title="No notifications" text="You're all caught up." /> : (
            <div>{q.data?.items.map((n: any) => {
              const Icon = ICONS[n.type] ?? Bell
              return (
                <div key={n.id} className={`notif ${n.read_at ? '' : 'unread'}`}>
                  <div className="notif-icon"><Icon size={17} /></div>
                  <div style={{ flex: 1, minWidth: 0 }}>
                    <div className="notif-title" style={{ fontWeight: 600 }}>{n.title}</div>
                    <div className="small">{n.message}</div>
                    <div className="small muted row mt-8" style={{ gap: 10, flexWrap: 'wrap' }}>
                      <span title={dateTime(n.created_at)}>{relative(n.created_at)}</span>
                      <span className="row" style={{ gap: 4 }}><Mail size={12} /> {EMAIL_LABEL[n.email_status] ?? n.email_status}</span>
                      {n.email_status === 'failed' && n.email_error && <Badge text={n.email_error} kind="danger" />}
                    </div>
                  </div>
                  <div className="row" style={{ alignSelf: 'center' }}>
                    {n.link && <button className="btn xs" onClick={() => { if (!n.read_at) mark.mutate({ id: n.id, read: true }); nav(n.link) }}>Open</button>}
                    <button className="btn xs ghost" onClick={() => mark.mutate({ id: n.id, read: !n.read_at })}>{n.read_at ? 'Mark unread' : 'Mark read'}</button>
                  </div>
                </div>
              )
            })}</div>
          )}
          {q.data && <Pagination page={page} pageSize={30} total={q.data.total} onPage={setPage} />}
        </QueryState>
      </div>
    </>
  )
}
